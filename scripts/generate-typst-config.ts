import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { author, cleanJobTitle, jobTitle, socialLinks } from '../src/config/site';

// Emits the identity constants and social links Typst content (post and
// page bodies) binds with eval(read(...)), keeping src/config/site.ts the
// single source. Content files reference this at
// ../../../generated/site.typ: both src/content/blog/<slug>/ and
// src/content/pages/<slug>/ are three levels below src/.
//
// Social links are exposed as social-<name> constants, one per socialLinks
// entry, so prose can reference them (#link(social-email)[email me]) and
// the rehype pipeline still derives the matching GoatCounter event from
// the equal href.
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const OUTPUT_PATH = path.resolve(__dirname, '../src/generated/site.typ');

const escapeTypstString = (s: string) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

async function main() {
  const social = Object.entries(socialLinks).map(([key, href]) => ({
    name: `social-${key}`,
    value: String(href),
  }));

  const lines = [
    '// Generated by scripts/generate-typst-config.ts from src/config/site.ts.',
    '// Do not edit; regenerate with `npm run generate:typst-config`.',
    '// Written in code mode (no leading `#`): callers evaluate it with',
    '// eval(read(...), mode: "code") and destructure the dictionary below',
    '// (a single-name binding needs a trailing comma to form a pattern).',
    `let author = "${escapeTypstString(author)}"`,
    `let jobTitle = "${escapeTypstString(jobTitle)}"`,
    `let cleanJobTitle = "${escapeTypstString(cleanJobTitle)}"`,
    ...social.map(({ name, value }) => `let ${name} = "${escapeTypstString(value)}"`),
    '',
    '(',
    '  author: author,',
    '  jobTitle: jobTitle,',
    '  cleanJobTitle: cleanJobTitle,',
    ...social.map(({ name }) => `  ${name}: ${name},`),
    ')',
    '',
  ];

  await fs.writeFile(OUTPUT_PATH, lines.join('\n'), 'utf8');
  console.log(`[typst-config] wrote ${path.relative(process.cwd(), OUTPUT_PATH)}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
